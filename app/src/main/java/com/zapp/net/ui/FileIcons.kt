 * each one has a drawable behind it - a name in a map with no `when` branch in [iconResOf] would
 * otherwise fail silently as a blank row.
 */
internal fun allIconNames(): Set<String> =
    FILE_NAMES.values.toSet() + FILE_EXTENSIONS.values + FOLDER_NAMES.values + "Document"
