/** Their `basenameOf`: backslashes count as separators, and empty segments are dropped. */
private fun basenameOf(p: String): String =
    p.replace('\\', '/').split('/').filter { it.isNotEmpty() }.lastOrNull() ?: ""

/** Their `folderNameVariants`: a folder is matched as `name`, `.name`, `_name` or `__name__`. */
private fun folderNameVariants(name: String): List<String> {
    val n = name.lowercase()
    return listOf(n, ".$n", "_$n", "__${n}__")
}

/** Their `dottedSuffixesDesc`: the whole name plus every suffix after a dot, longest first. */
private fun dottedSuffixesDesc(name: String): List<String> {
    val n = name.lowercase()
    val out = LinkedHashSet<String>()
    out.add(n)
    for (i in n.indices) if (n[i] == '.' && i + 1 < n.length) out.add(n.substring(i + 1))
    return out.sortedByDescending { it.length }
}

/** Their `toOpenVariant`: every folder icon has a generated `Open` twin, light ones included. */
private fun toOpenVariant(icon: String): String = when {
    !icon.startsWith("Folder") -> icon
    icon.endsWith("_light") -> icon.replace("_light", "Open_light")
    !icon.endsWith("Open") -> icon + "Open"
    else -> icon
}

/**
 * `chooseIconName` (`:498-515`), unchanged: exact file name first, then the longest dotted suffix,
 * then the default; folders try their four name variants, then the open/closed default.
 */
internal fun chooseIconName(path: String, isDirectory: Boolean, expanded: Boolean = false): String {
    val base = basenameOf(path).lowercase()
    if (isDirectory) {
        for (cand in folderNameVariants(base)) {
            val icon = FOLDER_NAMES[cand] ?: continue
            return if (expanded) toOpenVariant(icon) else icon
        }
        return if (expanded) "FolderOpen" else "Folder"
    }
    FILE_NAMES[base]?.let { return it }
    for (ext in dottedSuffixesDesc(base)) FILE_EXTENSIONS[ext]?.let { return it }
    return "Document"
}

/**
